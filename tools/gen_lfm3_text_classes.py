"""Generate native/include/lfm/lfm3_text_classes.hpp from the measured pre-tokenizer classes.

Input: the output of probe_pretokenizer_classes.py (classes measured through the real tokenizer's
Oniguruma regex, not a Unicode library). Output: sorted, disjoint code-point range tables for \\p{L},
\\p{N} and \\s as that regex sees them, plus the measured contraction folds. The header records the
input's sha256 so the tables can be traced to the measurement.

Usage: python gen_lfm3_text_classes.py CLASSES.json OUTPUT.hpp
"""
import hashlib
import json
from pathlib import Path
import sys


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    d = json.loads(src.read_text())
    cls = d["classes"]
    space = {cp for a, b in cls["space"]["ranges"] + cls["newline/carriage_return"]["ranges"] for cp in range(a, b + 1)}
    unclassified = d["unclassified_signatures"]
    if len(unclassified) != 1:
        raise SystemExit(f"expected exactly one extra (whitespace) signature group, found {len(unclassified)}")
    (ws_group,) = unclassified.values()
    space |= {cp for a, b in ws_group["ranges"] for cp in range(a, b + 1)}
    if len(space) != 25:
        raise SystemExit(f"expected the 25 Unicode White_Space characters, found {len(space)}")
    covered = cls["letter"]["count"] + cls["number"]["count"] + cls["other"]["count"] + len(space)
    if covered != d["total_code_points"]:
        raise SystemExit(f"classes cover {covered} of {d['total_code_points']} code points")

    # Measured contraction letters: single-letter suffixes accept these (case folding incl. U+017F).
    letters = {cp for a, b in cls["letter"]["ranges"] for cp in range(a, b + 1)}
    single = sorted({cp for _, cp in d["contraction_characters"]["s"] if cp in letters})
    expect_single = sorted(map(ord, "DMSTdmst")) + [0x17F]
    if single != sorted(expect_single):
        raise SystemExit(f"unexpected single-letter contraction set {single}")

    def ranges(name, rs):
        body = ",\n".join(f"    {{0x{a:X}, 0x{b:X}}}" for a, b in rs)
        return f"inline constexpr CodeRange {name}[] = {{\n{body}\n}};\n"

    def to_ranges(points):
        out, start, prev = [], None, None
        for p in sorted(points):
            if start is None:
                start = prev = p
            elif p == prev + 1:
                prev = p
            else:
                out.append((start, prev)); start = prev = p
        out.append((start, prev))
        return out

    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    header = f"""#pragma once
// GENERATED by tools/gen_lfm3_text_classes.py from {src.name} (sha256 {digest}).
// Character classes of LFM3's pre-tokenizer regex as the real tokenizer (tokenizers {d["versions"]["tokenizers"]},
// Oniguruma) evaluates them, measured code point by code point through that library. Do not edit by hand.
#include <cstdint>

namespace lfm::lfm3_text {{
struct CodeRange {{ std::uint32_t first, last; }};
{ranges("kLetter", cls["letter"]["ranges"])}
{ranges("kNumber", cls["number"]["ranges"])}
{ranges("kSpace", to_ranges(space))}
// Contraction letters (?i:'s|'t|'m|'d) accept: D M S T d m s t and U+017F (long s, folds to s).
// 're / 've / 'll accept only ASCII r R e E v V l L (measured).
inline constexpr std::uint32_t kLongS = 0x17F;
inline constexpr int kLetterCount = {cls["letter"]["count"]}, kNumberCount = {cls["number"]["count"]}, kSpaceCount = {len(space)};
}}  // namespace lfm::lfm3_text
"""
    dst.write_text(header)
    print(f"wrote {dst}: letters {cls['letter']['count']} in {len(cls['letter']['ranges'])} ranges, "
          f"numbers {cls['number']['count']}, whitespace {len(space)}")


if __name__ == "__main__":
    main()
