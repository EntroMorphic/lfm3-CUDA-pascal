#!/usr/bin/env python3
"""validation/speech-long-form-v1/report.md: the long-form TTS investigation's tables, from the committed ASR records.

Per configuration and case: WER over 15 seeds (mean, median, max, runs above 0.3), against the bar (HF BF16
unsplit) or the first row: the mean difference with a bootstrap 95% CI (20,000 resamples, Random(0)) and a two-sided
Mann-Whitney p. Onsets: the reference word index where each run's first error of two or more consecutive words
(a skip or a repeat) begins, from a word-level Levenshtein alignment of the normalized transcript to the text.
Every row must hold exactly the expected seeds (1-15 unless stated), or the report fails rather than average fewer.
Section 0 is the C1 escalations (validation/speech-e2e-v1) over seeds 1-15, and over the fresh seeds 4-15 alone
(the seeds that raised a flag are in 1-3, so 1-15 is biased toward confirming it).
Usage: lfm3_speech_long_form_report.py VALIDATION_DIR (the repo's validation/; writes speech-long-form-v1/report.md)
"""
import json
import random
import statistics as st
import sys
from collections import Counter
from pathlib import Path

from scipy.stats import mannwhitneyu


def align(ref, hyp):
    n, m = len(ref), len(hyp)
    D = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n + 1):
        D[i][0] = i
    for j in range(m + 1):
        D[0][j] = j
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            D[i][j] = min(D[i - 1][j] + 1, D[i][j - 1] + 1, D[i - 1][j - 1] + (ref[i - 1] != hyp[j - 1]))
    ops, i, j = [], n, m
    while i or j:
        if i and j and D[i][j] == D[i - 1][j - 1] + (ref[i - 1] != hyp[j - 1]):
            ops.append(("=" if ref[i - 1] == hyp[j - 1] else "S", i - 1)); i -= 1; j -= 1
        elif i and D[i][j] == D[i - 1][j] + 1:
            ops.append(("D", i - 1)); i -= 1
        else:
            ops.append(("I", i)); j -= 1
    return ops[::-1]


def onset(r):
    ops = align(r["normalized_intended"].split(), r["normalized_transcript"].split())
    return next((ops[k][1] for k in range(len(ops) - 1) if ops[k][0] != "=" and ops[k + 1][0] != "="), None)


def runs(files, case, seeds=range(1, 16)):
    out = {}
    for f in files:
        for r in json.load(open(f))["results"]:
            if r["case"].rsplit("-s", 1)[0] == case:
                s = int(r["case"].rsplit("-s", 1)[1])
                if s in out:
                    raise SystemExit(f"{case}: seed {s} twice in {files}")
                out[s] = r
    if sorted(out) != list(seeds):
        raise SystemExit(f"{case}: seeds {sorted(out)} in {files}, expected {list(seeds)}")
    return [out[s] for s in sorted(out)]


def table(rows, case, lines, seeds=range(1, 16)):
    rng = random.Random(0)
    lines += [f"### {case}", "", "| configuration | n | WER mean | median | max | runs > 0.3 | vs first row (95% CI) | Mann-Whitney p | onsets (word index) |",
              "|---|---|---|---|---|---|---|---|---|"]
    bar = None
    for label, files in rows:
        rs = runs(files, case, seeds)
        w = [r["wer"] for r in rs]
        bar = w if bar is None else bar
        d = sorted(st.mean(rng.choices(w, k=len(w))) - st.mean(rng.choices(bar, k=len(bar))) for _ in range(20000))
        ons = Counter(o for o in map(onset, rs) if o is not None)
        lines.append(f"| {label} | {len(w)} | {st.mean(w):.3f} | {st.median(w):.3f} | {max(w):.2f} | {sum(x > 0.3 for x in w)} | "
                     f"{st.mean(w) - st.mean(bar):+.3f} ({d[500]:+.3f}, {d[19500]:+.3f}) | {mannwhitneyu(w, bar).pvalue:.3f} | "
                     f"{', '.join(f'{k}x{v}' if v > 1 else str(k) for k, v in sorted(ons.items())) or 'none'} |")
    lines.append("")


def main(vdir):
    v = Path(vdir)
    e, a = v / "speech-e2e-v1" / "rounds", v / "speech-long-form-v1" / "asr"
    hf = [e / "e2e" / "asr-hf.json", e / "long" / "asr-hf.json"]
    nat = [e / "e2e" / "asr-native-cases.json", e / "long" / "asr-native-cases.json"]
    lines = ["# Long-form TTS: the tables (generated by tools/lfm3_speech_long_form_report.py)", ""]
    long, fridge = [e / "long" / "asr-hf.json"], [e / "fridge" / "asr-hf.json"]
    lines += ["## 0. The C1 escalations (speech-e2e-v1): HF BF16 against native", "", "Seeds 1-15:", ""]
    for case, extra in (("tts-numbers-female", "long"), ("il-fridge", "fridge"), ("tts-long-male", "long")):
        table([("HF BF16", [e / "e2e" / "asr-hf.json", e / extra / "asr-hf.json"]),
               ("native", [e / "e2e" / "asr-native-cases.json", e / extra / "asr-native-cases.json"])], case, lines)
    lines += ["Fresh seeds 4-15 only:", ""]
    for case, extra in (("tts-numbers-female", "long"), ("il-fridge", "fridge"), ("tts-long-male", "long")):
        table([("HF BF16", [e / extra / "asr-hf.json"]), ("native", [e / extra / "asr-native-cases.json"])], case, lines,
              range(4, 16))
    lines += ["## 1. Which numerics loop (tts-long-male, unsplit)", ""]
    table([("HF BF16 / BF16 (the bar)", hf), ("native (BF16-class LM / exact depth)", nat),
           ("HF BF16 LM / FP32 depth", [a / "hf-bf16lm-fp32depth.json"]), ("HF FP32 LM / BF16 depth", [a / "hf-fp32lm-bf16depth.json"]),
           ("HF FP32 / FP32 (the true model)", [a / "hf-fp32.json"])], "tts-long-male", lines)
    lines += ["Native against the FP32 model directly:", ""]
    table([("HF FP32 / FP32", [a / "hf-fp32.json"]), ("native", nat)], "tts-long-male", lines)
    lines += ["## 2. Widening the sliding window at inference (FP32 model, unsplit)", ""]
    table([("HF BF16, window 256 (the bar)", hf), ("HF FP32, window 256 (as trained)", [a / "hf-fp32.json"]),
           ("HF FP32, window 512", [a / "hf-fp32-window512.json"]), ("HF FP32, window 4096", [a / "hf-fp32-window4096.json"])],
          "tts-long-male", lines)
    lines += ["## 3. Position, not content (native, unsplit)", ""]
    for case in ("probe-hazard-alone", "probe-weather-alone", "probe-first-three", "probe-hazard-first", "probe-other-long"):
        table([("native", [a / "native-probes.json"])], case, lines)
    lines += ["## 4. The fix: one request per sentence", ""]
    table([("HF BF16 unsplit (the bar)", hf), ("native unsplit", nat), ("HF FP32 split", [a / "hf-fp32-split.json"]),
           ("HF BF16 split", [a / "hf-bf16-split.json"]), ("native split", [a / "native-split.json"])], "tts-long-male", lines)
    table([("native unsplit", [a / "native-probes.json"]), ("HF FP32 split", [a / "hf-fp32-split.json"]),
           ("HF BF16 split", [a / "hf-bf16-split.json"]), ("native split", [a / "native-split.json"])], "probe-other-long", lines)
    out = v / "speech-long-form-v1" / "report.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
